import { describe, expect, it } from "vitest";
import { ConvexError } from "convex/values";
import {
  alternativeAccessibleName,
  alternativeAuthorLine,
  alternativeCounter,
  alternativeSwitchErrorMessage,
  canEditTurn,
} from "./alternatives";

describe("alternatives copy", () => {
  it("names who made an alternative, 'you' for your own", () => {
    expect(alternativeAuthorLine("edit", "Avery Lane", true)).toBe("Edited by you");
    expect(alternativeAuthorLine("regenerate", "Jordan Reyes", false)).toBe("Regenerated by Jordan Reyes");
    expect(alternativeAuthorLine("edit", undefined, false)).toBeNull();
    expect(alternativeAuthorLine(undefined, "Avery Lane", true)).toBeNull();
  });

  it("counts '2 / 3' and names it 'Response 2 of 3'", () => {
    expect(alternativeCounter({ index: 2, count: 3 })).toBe("2 / 3");
    expect(alternativeAccessibleName({ index: 2, count: 3 })).toBe("Response 2 of 3");
  });

  it("explains a switch refused while a reply runs", () => {
    expect(alternativeSwitchErrorMessage(new ConvexError({ code: "CHAT_TURN_ACTIVE", message: "busy" })))
      .toBe("Wait for the reply to finish, then switch responses.");
    expect(alternativeSwitchErrorMessage(new Error("[CONVEX M(x)] boom"))).not.toContain("CONVEX M(");
  });
});

describe("canEditTurn", () => {
  it("offers Edit on a finished turn a person sent", () => {
    for (const status of ["completed", "failed", "aborted"]) {
      expect(canEditTurn({ status, promptMessageId: "p" })).toBe(true);
    }
    expect(canEditTurn({ status: "running", promptMessageId: "p" })).toBe(false);
    expect(canEditTurn({ status: "queued", promptMessageId: "p" })).toBe(false);
    expect(canEditTurn({ status: "completed", origin: "auto_continue", promptMessageId: "p" })).toBe(false);
    expect(canEditTurn(undefined)).toBe(false);
  });
});
